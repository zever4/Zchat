// Package blobstore contains an unexposed ciphertext filesystem primitive.
// It grants no HTTP access, database authorization, quota release or PG Ready.
// The coordinator must reserve full physical bytes and fence the current attempt
// BEFORE Write, and claim Deleting/cancel and join writers/readers BEFORE Remove.
// Accounting read leases pin exact artifacts but grant no database/JWT access.
// Direct primitive callers are trusted internal filesystem code; coordinators
// additionally own authentication, stream cancellation and shutdown joins.
package blobstore

import (
	"context"
	"crypto/sha256"
	"errors"
	"io"
	"io/fs"
	"os"
	"sync"
	"time"

	"github.com/google/uuid"
	boundary "github.com/zever4/Zchat/internal/e2ee"
)

var (
	ErrInvalid     = errors.New("invalid ciphertext storage input")
	ErrRoot        = errors.New("ciphertext storage root is not private and owned")
	ErrBusy        = errors.New("ciphertext storage operation already active or at capacity")
	ErrConflict    = errors.New("ciphertext attempt already exists")
	ErrIntegrity   = errors.New("ciphertext size or digest mismatch")
	ErrHeadroom    = errors.New("ciphertext storage has insufficient disk headroom")
	ErrClosed      = errors.New("ciphertext storage is closed")
	ErrUnsupported = errors.New("ciphertext storage requires Linux filesystem semantics")
)

const bufferBytes = 32 << 10

type Config struct {
	MaxConcurrent int
	HeadroomBytes uint64
	WriteTimeout  time.Duration
}

// AttemptID is generated by the server, never a client filename or path.
type Attempt struct {
	ID     string
	Bytes  int64
	SHA256 [32]byte
}

// Written means only that this process synced/closed/published exact bytes.
// It is NOT Ready, a Send receipt or permission to infer startup orphan state.
type Written struct {
	attempt   Attempt
	storageID string
}

func (w *Written) StorageID() string {
	if w == nil {
		return ""
	}
	return w.storageID
}

func (w *Written) Attempt() Attempt {
	if w == nil {
		return Attempt{}
	}
	return w.attempt
}

type Store struct {
	mu             sync.Mutex
	root           *os.Root
	owner          *os.File
	fs             filesystem
	available      func() (uint64, error)
	config         Config
	active         map[string]int64
	readers        map[string]int
	readCount      int
	reserved       uint64
	closed         bool
	storageID      string
	accounted      bool
	physicalActive int
}

// Capacity is immutable and lets the coordinator leave a slot for cleanup.
func (s *Store) Capacity() int     { return s.config.MaxConcurrent }
func (s *Store) StorageID() string { return s.storageID }

// Open pins an EXISTING private directory and an exclusive process lock. It
// never chmods/adopts an unsafe directory or treats existing files as Ready.
// Keep this root outside publicly served uploads. Its ancestry/configuration
// must be trusted; a malicious process with the same OS UID is out of scope.
func Open(path string, c Config) (*Store, error) {
	if c.MaxConcurrent < 1 || c.MaxConcurrent > 64 || c.HeadroomBytes == 0 || c.WriteTimeout <= 0 || c.WriteTimeout > 5*time.Minute {
		return nil, ErrInvalid
	}
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return nil, ErrRoot
	}
	r, err := os.OpenRoot(path)
	if err != nil {
		return nil, err
	}
	owner, err := lockRoot(r)
	if err != nil {
		r.Close()
		return nil, err
	}
	id, err := rootIdentity(r)
	if err != nil {
		owner.Close()
		r.Close()
		return nil, err
	}
	s := &Store{root: r, owner: owner, fs: rootFilesystem{r}, config: c, active: make(map[string]int64), readers: make(map[string]int), storageID: id}
	s.available = func() (uint64, error) { return diskAvailable(owner) }
	return s, nil
}

func validID(id string) bool {
	u, err := uuid.Parse(id)
	return err == nil && u.Version() == 4 && u.Variant() == uuid.RFC4122 && u.String() == id
}

func (s *Store) begin(ctx context.Context, id string, n int64) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return ErrClosed
	}
	if _, ok := s.active[id]; ok || s.readers[id] != 0 || len(s.active) >= s.config.MaxConcurrent {
		return ErrBusy
	}
	if n > 0 {
		free, err := s.available()
		if err != nil {
			return err
		}
		// Subtractions avoid overflow; charge other concurrent full writes even
		// if some of their bytes are already reflected by statfs (conservative).
		if free < s.config.HeadroomBytes || free-s.config.HeadroomBytes < s.reserved || free-s.config.HeadroomBytes-s.reserved < uint64(n) {
			return ErrHeadroom
		}
		s.reserved += uint64(n)
	}
	s.active[id] = n
	return nil
}
func (s *Store) end(id string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.reserved -= uint64(s.active[id])
	delete(s.active, id)
}

// Write owns src immediately, including admission failures. Close MUST unblock
// a concurrent Read (as required of HTTP request bodies). Cancellation closes
// the source; its callback is joined before returning/releasing the operation.
// At most 32KiB per admitted operation is buffered. No goroutine per read/write.
// A write error never authorizes quota release: Remove must subsequently finish
// after the caller has fenced/joined writers, even if best-effort cleanup worked.
func (s *Store) Write(ctx context.Context, a Attempt, src io.ReadCloser) (result *Written, err error) {
	if src == nil {
		return nil, ErrInvalid
	}
	ctx, cancel := context.WithTimeout(ctx, s.config.WriteTimeout)
	defer cancel()
	closeSource := sync.OnceValue(src.Close)
	defer func() {
		err = errors.Join(err, closeSource())
		if err != nil {
			result = nil
		}
	}()
	if !validID(a.ID) || a.Bytes <= boundary.AttachmentBlobOverhead || a.Bytes > boundary.MaxAttachmentBlobBytes {
		return nil, ErrInvalid
	}
	if err = s.begin(ctx, a.ID, a.Bytes); err != nil {
		return nil, err
	}
	defer func() { closeSource(); s.end(a.ID) }()
	joined := make(chan struct{})
	stop := context.AfterFunc(ctx, func() { defer close(joined); closeSource() })
	finishSource := sync.OnceFunc(func() {
		if !stop() {
			<-joined
		}
	})
	defer finishSource()
	part, final := a.ID+".part", a.ID+".blob"
	if _, err = s.fs.Lstat(final); err == nil {
		return nil, ErrConflict
	} else if !errors.Is(err, fs.ErrNotExist) {
		return nil, err
	}
	f, err := s.fs.OpenExclusive(part)
	if errors.Is(err, fs.ErrExist) {
		return nil, ErrConflict
	}
	if err != nil {
		return nil, err
	}
	closed, published := false, false
	defer func() {
		if !closed {
			err = errors.Join(err, f.Close())
		}
		finishSource()
		err = errors.Join(err, closeSource())
		if err != nil {
			err = errors.Join(err, removeLeaf(s.fs, part))
			if published {
				err = errors.Join(err, removeLeaf(s.fs, final))
			}
			err = errors.Join(err, s.fs.SyncDirectory())
			result = nil
		}
	}()
	if err = copyExact(ctx, f, src, a); err != nil {
		return nil, err
	}
	if err = f.Sync(); err != nil {
		return nil, err
	}
	err = f.Close()
	closed = true
	if err != nil {
		return nil, err
	}
	finishSource()
	if err = closeSource(); err != nil {
		return nil, err
	}
	if err = ctx.Err(); err != nil {
		return nil, err
	}
	// Hard-link publication is atomic and refuses an existing target. Rename
	// would overwrite it on Unix. Both names refer to one inode, not two copies.
	if err = s.fs.Link(part, final); err != nil {
		return nil, err
	}
	published = true
	if err = s.fs.SyncDirectory(); err != nil {
		return nil, err
	}
	if err = s.fs.Remove(part); err != nil {
		return nil, err
	}
	if err = s.fs.SyncDirectory(); err != nil {
		return nil, err
	}
	if err = ctx.Err(); err != nil {
		return nil, err
	}
	return &Written{attempt: a, storageID: s.storageID}, nil
}

func copyExact(ctx context.Context, dst io.Writer, src io.Reader, a Attempt) error {
	var buf [bufferBytes]byte
	h := sha256.New()
	remaining := a.Bytes
	empty := 0
	for remaining > 0 {
		if err := ctx.Err(); err != nil {
			return err
		}
		size := min(int64(len(buf)), remaining)
		n, err := src.Read(buf[:size])
		if e := ctx.Err(); e != nil {
			return e
		}
		if n < 0 || int64(n) > size {
			return ErrIntegrity
		}
		if n > 0 {
			if e := ctx.Err(); e != nil {
				return e
			}
			written, e := dst.Write(buf[:n])
			if e != nil {
				return e
			}
			if written != n {
				return io.ErrShortWrite
			}
			h.Write(buf[:n])
			remaining -= int64(n)
			empty = 0
		} else {
			empty++
			if empty >= 100 {
				return io.ErrNoProgress
			}
		}
		if err != nil {
			if err == io.EOF && remaining == 0 {
				break
			}
			if err == io.EOF {
				return ErrIntegrity
			}
			return err
		}
	}
	// Probe for excess without EVER writing beyond reserved bytes. Do not
	// let an io.ReaderTo/WriterFrom fast path bypass size/hash/context checks.
	for range 100 {
		if err := ctx.Err(); err != nil {
			return err
		}
		n, err := src.Read(buf[:1])
		if e := ctx.Err(); e != nil {
			return e
		}
		if n != 0 {
			return ErrIntegrity
		}
		if err == io.EOF {
			if [32]byte(h.Sum(nil)) != a.SHA256 {
				return ErrIntegrity
			}
			return nil
		}
		if err != nil {
			return err
		}
	}
	return io.ErrNoProgress
}

// Remove is idempotent durable reclamation of this attempt's two fixed names.
// Caller must first claim Deleting in PG, cancel and join its producers/readers.
// The process lock and active map prevent open handles owned by THIS store.
// Errors preserve the caller's physical reservation; TTL alone never calls this.
func (s *Store) Remove(ctx context.Context, id string) error {
	r, err := s.RemoveVerified(ctx, id)
	if err != nil {
		return err
	}
	return r.Close()
}

// Removed keeps the attempt's operation slot and root ownership until Close.
// Guard lets a DB commit use the live, root-bound unlink+directory-Sync proof;
// a concurrent Close waits for that commit. No plaintext or key is carried.
type Removed struct {
	mu     sync.Mutex
	store  *Store
	id     string
	closed bool
}

func (r *Removed) Guard(storageID, id string, commit func() error) error {
	if r == nil || commit == nil {
		return ErrInvalid
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.store == nil || r.closed || r.id != id || r.store.storageID != storageID {
		return ErrInvalid
	}
	return commit()
}
func (r *Removed) Close() error {
	if r == nil {
		return nil
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	if !r.closed && r.store != nil {
		r.closed = true
		r.store.end(r.id)
	}
	return nil
}

func (s *Store) RemoveVerified(ctx context.Context, id string) (*Removed, error) {
	if !validID(id) {
		return nil, ErrInvalid
	}
	if err := s.begin(ctx, id, 0); err != nil {
		return nil, err
	}
	err := errors.Join(removeLeaf(s.fs, id+".part"), removeLeaf(s.fs, id+".blob"))
	err = errors.Join(err, s.fs.SyncDirectory())
	if err != nil {
		s.end(id)
		return nil, err
	}
	return &Removed{store: s, id: id}, nil
}

func removeLeaf(f filesystem, name string) error {
	info, err := f.Lstat(name)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() && info.Mode()&os.ModeSymlink == 0 {
		return ErrRoot
	}
	err = f.Remove(name)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	return err
}

// Close refuses to drop process ownership until every operation has returned.
func (s *Store) Close() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return nil
	}
	if len(s.active) > 0 || s.readCount > 0 || s.physicalActive > 0 {
		return ErrBusy
	}
	s.closed = true
	return errors.Join(s.owner.Close(), s.root.Close())
}

type writerFile interface {
	io.Writer
	Sync() error
	Close() error
}
type filesystem interface {
	Lstat(string) (fs.FileInfo, error)
	OpenExclusive(string) (writerFile, error)
	Link(string, string) error
	Remove(string) error
	SyncDirectory() error
}
type rootFilesystem struct{ root *os.Root }

func (f rootFilesystem) Lstat(n string) (fs.FileInfo, error) { return f.root.Lstat(n) }
func (f rootFilesystem) OpenExclusive(n string) (writerFile, error) {
	return f.root.OpenFile(n, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
}
func (f rootFilesystem) Link(a, b string) error { return f.root.Link(a, b) }
func (f rootFilesystem) Remove(n string) error  { return f.root.Remove(n) }
func (f rootFilesystem) SyncDirectory() error {
	d, err := f.root.Open(".")
	if err != nil {
		return err
	}
	return errors.Join(d.Sync(), d.Close())
}
