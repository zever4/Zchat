//! Private prekey values, inside the existing AEAD framing/schema.
//! v1 live/legacy-used: [1,used,last_resort] + serialized record.
//! v2 consumed: [2,1,0] + domain/kind/id-bound SHA256(record); no private bytes.
use super::*;

pub(super) enum Saved<'a> {
    Live { record: &'a [u8], last_resort: bool },
    LegacyConsumed(&'a [u8]),
    Consumed(&'a [u8]),
}

fn validate_material(kind: RecordKind, id: u32, record: &[u8]) -> CryptoResult<()> {
    let stored_id = match kind {
        RecordKind::EcPreKey => {
            let value = PreKeyRecord::deserialize(record)?;
            value.key_pair()?;
            u32::from(value.id()?)
        }
        RecordKind::SignedPreKey => {
            let value = SignedPreKeyRecord::deserialize(record)?;
            value.key_pair()?;
            u32::from(value.id()?)
        }
        RecordKind::PqPreKey => {
            let value = KyberPreKeyRecord::deserialize(record)?;
            value.key_pair()?;
            u32::from(value.id()?)
        }
        _ => return Err(CryptoError::Invalid),
    };
    if stored_id != id {
        return Err(CryptoError::Invalid);
    }
    Ok(())
}

pub(super) fn decode(kind: RecordKind, id: u32, value: &[u8]) -> CryptoResult<Saved<'_>> {
    match value {
        [2, 1, 0, digest @ ..]
            if digest.len() == 32
                && matches!(kind, RecordKind::EcPreKey | RecordKind::PqPreKey) =>
        {
            Ok(Saved::Consumed(digest))
        }
        [1, used @ 0..=1, lr @ 0..=1, record @ ..] if !record.is_empty() => {
            if (*lr == 1 && kind != RecordKind::PqPreKey)
                || (*used == 1 && (*lr == 1 || kind == RecordKind::SignedPreKey))
            {
                return Err(CryptoError::Invalid);
            }
            validate_material(kind, id, record)?;
            if *used == 1 {
                Ok(Saved::LegacyConsumed(record))
            } else {
                Ok(Saved::Live {
                    record,
                    last_resort: *lr == 1,
                })
            }
        }
        _ => Err(CryptoError::Invalid),
    }
}

fn fingerprint(kind: RecordKind, id: u32, record: &[u8]) -> [u8; 32] {
    let mut hash = Sha256::new();
    hash.update(b"zchat.e2ee.consumed-prekey.v2\0");
    hash.update([kind as u8]);
    hash.update(id.to_be_bytes());
    hash.update(record);
    hash.finalize().into()
}

pub(super) fn tombstone(kind: RecordKind, id: u32, record: &[u8]) -> Vec<u8> {
    [&[2, 1, 0], fingerprint(kind, id, record).as_slice()].concat()
}

// last_resort=None is the libsignal save callback: preserve an existing LR flag,
// default to one-time for a new key. Install supplies an explicit classification.
pub(super) fn save(
    tx: &mut ProtectedTransaction<'_>,
    generation: &str,
    kind: RecordKind,
    id: u32,
    record: &[u8],
    last_resort: Option<bool>,
) -> CryptoResult<()> {
    let key = RecordKey::new(generation, kind, &id.to_string())?;
    validate_material(kind, id, record)?;
    if last_resort == Some(true) && kind != RecordKind::PqPreKey {
        return Err(CryptoError::Invalid);
    }
    if let Some(old) = tx.get(&key)? {
        match decode(kind, id, &old)? {
            Saved::Live {
                record: saved,
                last_resort: lr,
            } if saved == record && last_resort.is_none_or(|wanted| wanted == lr) => (),
            Saved::LegacyConsumed(saved) if saved == record && last_resort != Some(true) => {
                tx.put(&key, &tombstone(kind, id, record))?;
            }
            Saved::Consumed(digest)
                if digest == fingerprint(kind, id, record) && last_resort != Some(true) => {}
            _ => return Err(CryptoError::Conflict),
        }
    } else {
        // New material must not fill an old gap or a burned reservation through
        // the legacy installation/callback path. A future refill plan will bind
        // generated bytes to its reservation in a separate atomic operation.
        prekey_ids::observe_new(tx, generation, kind, id)?;
        let value =
            Zeroizing::new([&[1, 0, u8::from(last_resort.unwrap_or(false))], record].concat());
        tx.put(&key, &value)?;
    }
    Ok(())
}

/// Opaque, account/generation-bound progress; no serialization/renderer cursor.
#[derive(Clone)]
pub struct PreKeyRedactionCursor {
    scope: StoreScope,
    generation: String,
    kind: RecordKind,
    after: Option<String>,
}
pub struct PreKeyRedactionPage {
    pub scanned: usize,
    pub redacted: usize,
    pub next: Option<PreKeyRedactionCursor>,
}

impl Engine {
    // Explicit maintenance, never a hidden scan/migration during store open.
    // Only current-generation, authenticated already-used records are rewritten.
    pub(super) fn redact_consumed_prekeys(
        &mut self,
        after: Option<PreKeyRedactionCursor>,
    ) -> CryptoResult<PreKeyRedactionPage> {
        let scope = self.store.scope().clone();
        let generation = self.own.generation_id.clone();
        let cursor = after.unwrap_or_else(|| PreKeyRedactionCursor {
            scope: scope.clone(),
            generation: generation.clone(),
            kind: RecordKind::EcPreKey,
            after: None,
        });
        if cursor.scope != scope
            || cursor.generation != generation
            || !matches!(cursor.kind, RecordKind::EcPreKey | RecordKind::PqPreKey)
        {
            return Err(CryptoError::Conflict);
        }
        self.store.transaction_with(|tx| {
            let rows = tx.record_page(&generation, cursor.kind, "", cursor.after.as_deref())?;
            let mut redacted = 0;
            for (id, bytes) in &rows {
                let numeric: u32 = id.parse().map_err(|_| CryptoError::Invalid)?;
                if numeric.to_string() != *id {
                    return Err(CryptoError::Invalid);
                }
                if let Saved::LegacyConsumed(record) = decode(cursor.kind, numeric, bytes)? {
                    tx.put(
                        &RecordKey::new(&generation, cursor.kind, id)?,
                        &tombstone(cursor.kind, numeric, record),
                    )?;
                    redacted += 1;
                }
            }
            let next = if rows.len() == 32 {
                Some(PreKeyRedactionCursor {
                    after: rows.last().map(|(id, _)| id.clone()),
                    ..cursor
                })
            } else if cursor.kind == RecordKind::EcPreKey {
                Some(PreKeyRedactionCursor {
                    kind: RecordKind::PqPreKey,
                    after: None,
                    ..cursor
                })
            } else {
                None
            };
            Ok(PreKeyRedactionPage {
                scanned: rows.len(),
                redacted,
                next,
            })
        })
    }
}
